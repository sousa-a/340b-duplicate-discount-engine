# test_synthetic_notice.py
#
# Every reader-facing text states that the data is synthetic. The READMEs, the config and the generator package
# say so in their own words ("completely synthetic", "... are synthetic"); every published doc in docs/ opens with the
# standard disclaimer below. The test
# fails when a file loses the statement, or when a new document is added without it.

import pathlib
import re

REPO = pathlib.Path(__file__).resolve().parents[1]
# Accepted wordings of the statement, e.g. "completely synthetic" or "All records ... are synthetic."
PHRASE = re.compile(r"completely synthetic|\b(?:is|are) synthetic\b", re.IGNORECASE)
DISCLAIMER = ("> All records generated by this project are synthetic. Real public data is used only for sourced "
              "parameters and seeds. See [SYNTHETIC_DATA_NOTICE.md](../SYNTHETIC_DATA_NOTICE.md).")
REQUIRED = ["README.md", "SYNTHETIC_DATA_NOTICE.md", "notebooks/README.md", "samples/README.md", "visuals/README.md"]
# Generator-side files stay out of the public repo for now (they move to a separate private repo later); they are
# checked only where they exist, so the same test runs in both places.
IF_PRESENT = ["config/generator.yml", "src/generator/__init__.py", "dbt/seeds/README.md"]


def test_required_files_state_the_data_is_synthetic():
    files = REQUIRED + [p for p in IF_PRESENT if (REPO / p).exists()]
    missing = [p for p in files if not PHRASE.search((REPO / p).read_text(encoding="utf-8"))]
    print(f"[notice] files checked: {len(files)}")
    assert not missing, f"no synthetic-data statement in: {missing}"


def test_every_doc_states_the_data_is_synthetic():
    docs = sorted((REPO / "docs").glob("*.md"))
    missing = [d.name for d in docs if DISCLAIMER not in d.read_text(encoding="utf-8").splitlines()]
    print(f"[notice] docs checked: {len(docs)}")
    assert docs and not missing, f"standard disclaimer missing in docs: {missing}"
